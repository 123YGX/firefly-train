    completed: new Set(),
    stars: {},

    saveProgress() {
        try {
            localStorage.setItem('ft_completed', JSON.stringify([...this.completed]));
            localStorage.setItem('ft_stars', JSON.stringify(this.stars));
        } catch (e) {}
    },

    loadProgress() {
        try {
            const raw = localStorage.getItem('ft_completed');
            if (raw) {
                const arr = JSON.parse(raw);
                this.completed = new Set(arr);
            }
            const rawStars = localStorage.getItem('ft_stars');
            if (rawStars) {
                this.stars = JSON.parse(rawStars) || {};
            }
        } catch (e) {}
    },

    markCurrentComplete(stars) {
        const key = `${this.currentChapter}-${this.currentLevel}`;
        this.completed.add(key);
        if (typeof stars === 'number' && stars > 0) {
            const prev = this.stars[key] || 0;
            if (stars > prev) this.stars[key] = stars;
        }
        this.saveProgress();
    },

    getStars(chapterIdx, levelIdx) {
        return this.stars[`${chapterIdx}-${levelIdx}`] || 0;
    },

    isLevelUnlocked(chapterIdx, levelIdx) {
        if (chapterIdx === 0 && levelIdx === 0) return true;
        if (levelIdx === 0) {
            const prevCh = this.data[chapterIdx - 1];
            return this.completed.has(`${chapterIdx - 1}-${prevCh.length - 1}`);
        }
        return this.completed.has(`${chapterIdx}-${levelIdx - 1}`);
    },

    isChapterUnlocked(chapterIdx) {
        return this.isLevelUnlocked(chapterIdx, 0);
    },

    isLevelCompleted(chapterIdx, levelIdx) {
        return this.completed.has(`${chapterIdx}-${levelIdx}`);
    },

