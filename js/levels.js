    isLevelUnlocked(chapterIdx, levelIdx) {
        if (chapterIdx === 0 && levelIdx === 0) return true;
        if (levelIdx === 0) {
            const prevCh = this.data[chapterIdx - 1];
            return this.completed.has(`${chapterIdx - 1}-${prevCh.length - 1}`);
        }
        return this.completed.has(`${chapterIdx}-${levelIdx - 1}`);
    },

    isChapterUnlocked(chapterIdx) {
        return this.isLevelUnlocked(chapterIdx, 0);
    },

    isLevelCompleted(chapterIdx, levelIdx) {
        return this.completed.has(`${chapterIdx}-${levelIdx}`);
    },

