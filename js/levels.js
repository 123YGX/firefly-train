    getCurrentLevel() {
        return this.data[this.currentChapter][this.currentLevel];
    },

    nextLevel() {
        this.currentLevel++;
        if (this.currentLevel >= this.data[this.currentChapter].length) {
            this.currentLevel = 0;
            this.currentChapter++;
            if (this.currentChapter >= this.data.length) {
                return 'gameover';
            }
            return 'newchapter';
        }
        return 'nextlevel';
    },

    getTotalLevels() {
        return this.data.reduce((sum, ch) => sum + ch.length, 0);
    }
